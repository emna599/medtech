-- Nettoyage (utile si tu relances le script)
DROP TABLE IF EXISTS staff_assignment CASCADE;
DROP TABLE IF EXISTS tour_revision, care_completion_receipt, resident_daily_entry, resident_daily_preferences, handover_action, auth_session, login_throttle, meal_instruction_change, audit_log, qr_code, meal_distribution, meal,
    dietary_regime, allergy, medical_record, resident, room, users CASCADE;

-- ---------- USERS (User est un mot réservé -> "users") ----------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(150) NOT NULL,
    role          VARCHAR(20)  NOT NULL
                  CHECK (role IN ('ADMIN', 'PERSONNEL', 'MEDECIN')),
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT NOW()
);

-- ---------- ROOM ----------
CREATE TABLE room (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number   VARCHAR(20) NOT NULL UNIQUE,
    floor    INT         NOT NULL,
    capacity INT         NOT NULL CHECK (capacity > 0)
);

-- ---------- RESIDENT ----------
CREATE TABLE resident (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     VARCHAR(100) NOT NULL,
    last_name      VARCHAR(100) NOT NULL,
    birth_date     DATE         NOT NULL,
    admission_date DATE         NOT NULL,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    room_id        BIGINT       REFERENCES room(id) ON DELETE SET NULL
);

-- ---------- MEDICAL RECORD (1 - 1 avec resident) ----------
CREATE TABLE medical_record (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    history     TEXT,
    treatments  TEXT,
    updated_at  TIMESTAMP NOT NULL DEFAULT NOW(),
    resident_id BIGINT NOT NULL UNIQUE
                REFERENCES resident(id) ON DELETE CASCADE
);

-- ---------- ALLERGY ----------
CREATE TABLE allergy (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    severity    VARCHAR(50),
    resident_id BIGINT NOT NULL
                REFERENCES resident(id) ON DELETE CASCADE
);

-- ---------- DIETARY REGIME ----------
CREATE TABLE dietary_regime (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(100) NOT NULL,
    restrictions TEXT,
    intolerances TEXT,
    instructions TEXT,
    resident_id  BIGINT NOT NULL
                 REFERENCES resident(id) ON DELETE CASCADE
);

-- ---------- MEAL ----------
CREATE TABLE meal (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(50) NOT NULL,
    description  TEXT,
    scheduled_at TIMESTAMP   NOT NULL,
    resident_id  BIGINT      NOT NULL
                 REFERENCES resident(id) ON DELETE CASCADE
);

-- ---------- MEAL DISTRIBUTION (1 repas -> 0..1 distribution) ----------
CREATE TABLE meal_distribution (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    served_at TIMESTAMP NOT NULL DEFAULT NOW(),
    comment   TEXT,
    meal_id   BIGINT NOT NULL UNIQUE
              REFERENCES meal(id) ON DELETE CASCADE,
    user_id   BIGINT NOT NULL
              REFERENCES users(id)
);

-- ---------- QR CODE ----------
CREATE TABLE qr_code (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token          VARCHAR(255) NOT NULL UNIQUE,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP    NOT NULL DEFAULT NOW(),
    deactivated_at TIMESTAMP,
    resident_id    BIGINT NOT NULL
                   REFERENCES resident(id) ON DELETE CASCADE,
    user_id        BIGINT REFERENCES users(id) ON DELETE SET NULL
);

-- ---------- AUDIT LOG ----------
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action      VARCHAR(100) NOT NULL,
    entity_type VARCHAR(100),
    entity_id   BIGINT,
    created_at  TIMESTAMP NOT NULL DEFAULT NOW(),
    user_id     BIGINT REFERENCES users(id) ON DELETE SET NULL
);

-- ---------- INDEX utiles ----------
CREATE INDEX idx_resident_room     ON resident(room_id);
CREATE INDEX idx_allergy_resident  ON allergy(resident_id);
CREATE INDEX idx_regime_resident   ON dietary_regime(resident_id);
CREATE INDEX idx_meal_resident     ON meal(resident_id);
CREATE INDEX idx_meal_scheduled    ON meal(scheduled_at);
CREATE INDEX idx_qr_resident       ON qr_code(resident_id);
CREATE INDEX idx_audit_user        ON audit_log(user_id);
CREATE INDEX idx_audit_created     ON audit_log(created_at);
