-- ---------- RESIDENT : photo, lieu du repas, aide, signes distinctifs ----------
ALTER TABLE resident ADD COLUMN IF NOT EXISTS photo_url              VARCHAR(255);
ALTER TABLE resident ADD COLUMN IF NOT EXISTS distinguishing_features VARCHAR(255);
ALTER TABLE resident ADD COLUMN IF NOT EXISTS meal_location          VARCHAR(20) NOT NULL DEFAULT 'SALLE';
ALTER TABLE resident ADD COLUMN IF NOT EXISTS needs_help             BOOLEAN     NOT NULL DEFAULT FALSE;
-- Identifiant ANONYME (contenu d'un éventuel QR de bracelet, facultatif) : jamais de donnée de santé.
ALTER TABLE resident ADD COLUMN IF NOT EXISTS identity_code          VARCHAR(50);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'resident_meal_location_chk') THEN
        ALTER TABLE resident ADD CONSTRAINT resident_meal_location_chk
            CHECK (meal_location IN ('SALLE', 'CHAMBRE'));
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS idx_resident_identity_code
    ON resident(identity_code) WHERE identity_code IS NOT NULL;

-- ---------- DIETARY_REGIME : texture des repas ----------
ALTER TABLE dietary_regime ADD COLUMN IF NOT EXISTS texture VARCHAR(50);

-- ---------- MEAL : statut du service (A_FAIRE / FAIT / REFUSE / PLUS_TARD) ----------
ALTER TABLE meal ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'A_FAIRE';
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'meal_status_chk') THEN
        ALTER TABLE meal ADD CONSTRAINT meal_status_chk
            CHECK (status IN ('A_FAIRE', 'FAIT', 'REFUSE', 'PLUS_TARD'));
    END IF;
END $$;

-- ---------- MEAL_DISTRIBUTION : quantité mangée (RIEN / QUART / MOITIE / TROIS_QUARTS / TOUT) ----------
ALTER TABLE meal_distribution ADD COLUMN IF NOT EXISTS quantity_eaten VARCHAR(20);

-- ---------- MEDICATION_DOSE : une prise de médicament prévue à une heure donnée ----------
CREATE TABLE IF NOT EXISTS medication_dose (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medication   VARCHAR(150) NOT NULL,
    dose         VARCHAR(100),
    scheduled_at TIMESTAMP    NOT NULL,
    high_risk    BOOLEAN      NOT NULL DEFAULT FALSE,
    status       VARCHAR(20)  NOT NULL DEFAULT 'A_FAIRE'
                 CHECK (status IN ('A_FAIRE', 'FAIT', 'REFUSE', 'PLUS_TARD')),
    given_at     TIMESTAMP,
    comment      TEXT,
    resident_id  BIGINT NOT NULL REFERENCES resident(id) ON DELETE CASCADE,
    user_id      BIGINT REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_dose_resident  ON medication_dose(resident_id);
CREATE INDEX IF NOT EXISTS idx_dose_scheduled ON medication_dose(scheduled_at);

-- ---------- IDENTITY_DOUBT : doute d'identité signalé par un soignant ----------
CREATE TABLE IF NOT EXISTS identity_doubt (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note        VARCHAR(255),
    created_at  TIMESTAMP NOT NULL DEFAULT NOW(),
    resolved    BOOLEAN   NOT NULL DEFAULT FALSE,
    resolved_at TIMESTAMP,
    resident_id BIGINT NOT NULL REFERENCES resident(id) ON DELETE CASCADE,
    reported_by BIGINT NOT NULL REFERENCES users(id),
    resolved_by BIGINT REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_doubt_resident ON identity_doubt(resident_id);

-- =====================================================
-- Version 2 : fonction du soignant, planning fixe, notes de traçabilité,
-- puces NFC et photos des résidents. Relançable (IF NOT EXISTS).
-- =====================================================

-- ---------- STAFF_PROFILE : fonction (infirmier / aide-soignant) et équipe de chaque soignant ----------
-- Sans ligne ici, un compte PERSONNEL est traité comme aide-soignant (pas de médicaments) ; ADMIN a tous les droits.
CREATE TABLE IF NOT EXISTS staff_profile (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    job     VARCHAR(20) NOT NULL CHECK (job IN ('INFIRMIER', 'AIDE_SOIGNANT', 'SERVICE')),
    shift   VARCHAR(10) NOT NULL DEFAULT 'JOUR' CHECK (shift IN ('JOUR', 'NUIT'))
);

-- ---------- PLANNING_TASK : planning type (fixe) par fonction et par équipe ----------
CREATE TABLE IF NOT EXISTS planning_task (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job        VARCHAR(20)  NOT NULL CHECK (job IN ('INFIRMIER', 'AIDE_SOIGNANT', 'SERVICE')),
    shift      VARCHAR(10)  NOT NULL CHECK (shift IN ('JOUR', 'NUIT')),
    start_time TIME         NOT NULL,
    end_time   TIME         NOT NULL,
    label      VARCHAR(150) NOT NULL,
    kind       VARCHAR(20)  NOT NULL CHECK (kind IN ('TRANSMISSION', 'TOURNEE', 'REPAS', 'SOINS', 'PAUSE')),
    focus      VARCHAR(20)  CHECK (focus IN ('REPAS', 'MEDICAMENT'))
);

-- ---------- STAFF_NOTE : notes de traçabilité (saisies au clavier ou à la voix) ----------
CREATE TABLE IF NOT EXISTS staff_note (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content     VARCHAR(1000) NOT NULL,
    category    VARCHAR(20)   NOT NULL DEFAULT 'TRACABILITE'
                CHECK (category IN ('TRACABILITE', 'OBSERVATION', 'INCIDENT')),
    created_at  TIMESTAMP     NOT NULL DEFAULT NOW(),
    user_id     BIGINT        NOT NULL REFERENCES users(id),
    resident_id BIGINT        REFERENCES resident(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_note_resident ON staff_note(resident_id);
CREATE INDEX IF NOT EXISTS idx_note_created  ON staff_note(created_at);

-- ---------- RESIDENT_NFC_TAG : contenu des puces NFC (médicaments et identification) ----------
CREATE TABLE IF NOT EXISTS resident_nfc_tag (
    token       VARCHAR(100) PRIMARY KEY,
    active      BOOLEAN   NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP NOT NULL DEFAULT NOW(),
    resident_id BIGINT    NOT NULL REFERENCES resident(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_nfc_resident ON resident_nfc_tag(resident_id);

-- ---------- RESIDENT_PHOTO : photo envoyée par l'administrateur ----------
CREATE TABLE IF NOT EXISTS resident_photo (
    resident_id  BIGINT PRIMARY KEY REFERENCES resident(id) ON DELETE CASCADE,
    content_type VARCHAR(50) NOT NULL,
    data         BYTEA       NOT NULL,
    updated_at   TIMESTAMP   NOT NULL DEFAULT NOW()
);

-- ---------- STAFF_PRESENCE : qui est en service (« Je prends mon service » / « Je termine mon service ») ----------
-- Sert à répartir les résidents entre les soignants présents. Une présence ouverte depuis plus de 16 h est ignorée.
CREATE TABLE IF NOT EXISTS staff_presence (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT    NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    started_at TIMESTAMP NOT NULL DEFAULT NOW(),
    ended_at   TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_presence_user ON staff_presence(user_id);

-- ---------- CHEVALET : numéro posé sur la table ou le plateau, associé à un résident ----------
-- Un chevalet n'est associé qu'à un résident à la fois, et un résident n'a qu'un chevalet.
CREATE TABLE IF NOT EXISTS chevalet (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(30) NOT NULL UNIQUE,
    resident_id   BIGINT UNIQUE REFERENCES resident(id) ON DELETE SET NULL,
    associated_at TIMESTAMP,
    associated_by BIGINT REFERENCES users(id) ON DELETE SET NULL
);

-- Bases créées avant la fonction SERVICE : on élargit les contraintes (sans effet si déjà fait)
ALTER TABLE staff_profile DROP CONSTRAINT IF EXISTS staff_profile_job_check;
ALTER TABLE staff_profile ADD CONSTRAINT staff_profile_job_check CHECK (job IN ('INFIRMIER', 'AIDE_SOIGNANT', 'SERVICE'));
ALTER TABLE planning_task DROP CONSTRAINT IF EXISTS planning_task_job_check;
ALTER TABLE planning_task ADD CONSTRAINT planning_task_job_check CHECK (job IN ('INFIRMIER', 'AIDE_SOIGNANT', 'SERVICE'));

-- ---------- DINING_TABLE : tables de la salle à manger (8 résidents au maximum par table) ----------
CREATE TABLE IF NOT EXISTS dining_table (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label    VARCHAR(30) NOT NULL UNIQUE,
    capacity INTEGER     NOT NULL DEFAULT 8 CHECK (capacity BETWEEN 1 AND 8)
);
-- Les résidents s'installent où ils veulent : plus de place attribuée (la présence vient des lecteurs RFID, voir table_presence).
DROP TABLE IF EXISTS dining_seat;

-- ---------- WEEKLY_MENU : menu de chaque semaine (week_start = lundi) ----------
-- Tant qu'aucun nouveau menu n'est saisi, celui de la dernière semaine renseignée se répète.
CREATE TABLE IF NOT EXISTS weekly_menu (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_start  DATE         NOT NULL,
    day_of_week INTEGER      NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    meal_type   VARCHAR(20)  NOT NULL CHECK (meal_type IN ('DEJEUNER', 'DINER')),
    starter     VARCHAR(150),
    main_course VARCHAR(150) NOT NULL,
    side        VARCHAR(150),
    dessert     VARCHAR(150),
    UNIQUE (week_start, day_of_week, meal_type)
);

-- ---------- TABLE_READER / TABLE_PRESENCE : lecteurs RFID de table et présence réelle des résidents ----------
-- Un lecteur (TR1, TR2...) est fixé à une table ; quand un bracelet est lu, le résident est marqué présent à cette table.
CREATE TABLE IF NOT EXISTS table_reader (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(30) NOT NULL UNIQUE,
    table_id BIGINT      NOT NULL UNIQUE REFERENCES dining_table(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS table_presence (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resident_id BIGINT    NOT NULL REFERENCES resident(id) ON DELETE CASCADE,
    table_id    BIGINT    NOT NULL REFERENCES dining_table(id) ON DELETE CASCADE,
    arrived_at  TIMESTAMP NOT NULL DEFAULT NOW(),
    left_at     TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_presence_resident ON table_presence(resident_id);

-- Hibernate attend des INTEGER : corrige les tables créées avec SMALLINT par une version précédente de ce script
ALTER TABLE dining_table ALTER COLUMN capacity    TYPE INTEGER;
ALTER TABLE weekly_menu  ALTER COLUMN day_of_week TYPE INTEGER;
