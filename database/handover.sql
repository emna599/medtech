BEGIN
    PERFORM pg_advisory_xact_lock(184933012);
    CREATE TABLE IF NOT EXISTS handover_action (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        request_id UUID NOT NULL,
        resident_id BIGINT REFERENCES resident(id),
        created_by BIGINT NOT NULL REFERENCES users(id),
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        observation TEXT NOT NULL CHECK (char_length(observation) BETWEEN 1 AND 1200),
        expected_action TEXT NOT NULL CHECK (char_length(expected_action) BETWEEN 1 AND 400),
        completed_by BIGINT REFERENCES users(id),
        completed_at TIMESTAMPTZ,
        UNIQUE (created_by, request_id),
        CHECK ((completed_by IS NULL) = (completed_at IS NULL))
    );
    CREATE INDEX IF NOT EXISTS idx_handover_open ON handover_action (created_at, id) WHERE completed_at IS NULL;
    CREATE INDEX IF NOT EXISTS idx_handover_completed ON handover_action (completed_at DESC, id DESC) WHERE completed_at IS NOT NULL;
END;
